-- Make a reused payment receipt impossible, and make every gateway check
-- something the shop keeps rather than something it renders once.
--
-- ## Safety on an existing database
--
-- Every statement here is additive. No column is dropped, no value is
-- rewritten, and nothing existing changes meaning: `transaction_id` keeps
-- whatever the customer typed, and the new column is derived from it.
--
-- Orders placed before this migration are unaffected. A manual transfer from
-- 2024 whose receipt was never collected has NULL in the new column, which the
-- unique index ignores and the panel renders as "no receipt on file" — the
-- same thing it said before.
--
-- Two statements do take a heavy lock on `orders`: adding a stored generated
-- column rewrites the table, and CREATE UNIQUE INDEX blocks writes while it
-- builds. Both are seconds on a table of this size. Neither is written
-- CONCURRENTLY because that cannot run inside a transaction, and running this
-- file transactionally is worth more here than avoiding a brief lock: if the
-- duplicate check below fails, everything above it must roll back.
--
-- ## If this migration fails
--
-- It fails on purpose, in one case: existing orders already sharing a receipt.
-- Read the message, run `npm run db:receipt-duplicates` for the full list, and
-- resolve those orders — cancel the ones that were never really paid for, or
-- refund them. Then run this again. Nothing will have been applied.
--> statement-breakpoint

