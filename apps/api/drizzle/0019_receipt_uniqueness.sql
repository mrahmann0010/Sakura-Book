-- The form two receipts are compared in. Generated by Postgres so it cannot
-- drift from the TypeScript that used to compute it separately — those two
-- disagreed about non-breaking spaces, which is a receipt that never matched
-- itself and so was never caught as a duplicate.
ALTER TABLE "orders" ADD COLUMN "transaction_id_normalised" text GENERATED ALWAYS AS (nullif(upper(regexp_replace(coalesce("transaction_id", ''), '[^A-Za-z0-9]', '', 'g')), '')) STORED;--> statement-breakpoint

-- Refuse to add the constraint over data that already violates it.
--
-- Without this the next statement fails on its own, with Postgres naming one
-- arbitrary duplicate key and nothing else. That is a genuinely bad thing to
-- hit halfway through a release: the error does not say how many orders are
-- involved, which they are, or what to do. This says all three.
--
-- Note the normalisation is stricter than the old application-level check —
-- it now ignores hyphens and underscores too — so a pair like `PAY-123` and
-- `PAY123` may be reported here even though nothing flagged it before. That is
-- the check working, not a false positive.
DO $$
DECLARE
	duplicate_count integer;
	sample text;
BEGIN
	SELECT count(*), string_agg(orders_involved, '; ')
	INTO duplicate_count, sample
	FROM (
		SELECT string_agg(order_number, ', ' ORDER BY created_at) AS orders_involved
		FROM orders
		WHERE transaction_id_normalised IS NOT NULL
			AND status <> 'CANCELLED'
			AND status <> 'REFUNDED'
		GROUP BY transaction_id_normalised
		HAVING count(*) > 1
		LIMIT 10
	) AS duplicates;

	IF duplicate_count > 0 THEN
		RAISE EXCEPTION
			'% receipt(s) are shared by more than one live order, so the uniqueness index cannot be created. Orders involved: %. Cancel or refund the orders that were not really paid for, then run this migration again. Nothing has been applied.',
			duplicate_count, sample
			USING HINT = 'Run `npm run db:receipt-duplicates` in apps/api for the full list.';
	END IF;
END
$$;--> statement-breakpoint

-- One live order per receipt. The application check in
-- `findTransactionIdClaim` stays — it is what names the conflicting order in
-- an error message — but this is what makes the rule true, including for two
-- checkouts that read before either commits.
--
-- Partial on status because a cancelled or refunded order has let go of its
-- claim: the money was never taken or has been sent back, and the customer
-- re-placing that order with the same receipt is doing the right thing.
CREATE UNIQUE INDEX "orders_transaction_id_live_unique_idx" ON "orders" USING btree ("transaction_id_normalised") WHERE "status" <> 'CANCELLED' AND "status" <> 'REFUNDED';
